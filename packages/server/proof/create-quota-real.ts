// 真 Host/service/SQLite 的无模型创建proof。租约时序另由CQ12/CQ13经真实Host/QuotaTable和受控适配器验证。
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import type { ContactView, RoomView, TaskView } from "@g-group/api-contract";
import { all, getDoc, run } from "../src/db.ts";
import { Host } from "../src/host.ts";
import { createService } from "../src/service.ts";
const root = mkdtempSync(path.join(os.tmpdir(), "gg-create-quota-real-"));
const file = path.join(root, "gg.db");
const mind = () => ({ async round() { return { actions: [], stateNote: null }; } });
let host = new Host({ file, dataDir: root, mind, maxDeferMs: 1 });
try {
  let svc = createService(host);
  const contactInput = { clientActionId: "proof-contact", name: "创建额度实跑", computeSlots: 2 };
  const created = await svc.handle("contacts.create", contactInput); assert.ok(created.ok);
  const contact = created.value as ContactView;
  const groupInput = { clientActionId: "proof-group", title: "创建群额度实跑", members: [{ kind: "contact", id: contact.id }], tempComputeSlots: 3 };
  const groupCreated = await svc.handle("rooms.createGroup", groupInput); assert.ok(groupCreated.ok);
  const group = groupCreated.value as RoomView;
  assert.deepEqual([host.contactDoc(contact.id).value.computeSlots, getDoc(host.db, `room-slots:${group.id}`)?.value], [2, { slots: 3 }]);
  assert.equal(host.contactHistory(contact.id).versions[0]!.config.computeSlots, 2);
  const badContact = await svc.handle("contacts.create", { ...contactInput, clientActionId: "bad-contact", computeSlots: 0 });
  const badGroup = await svc.handle("rooms.createGroup", { ...groupInput, clientActionId: "bad-group", tempComputeSlots: -1 });
  assert.deepEqual([!badContact.ok && badContact.error.code, !badGroup.ok && badGroup.error.code], ["invalid_params", "invalid_params"]);
  run(host.db, "CREATE TRIGGER proof_abort BEFORE INSERT ON actions WHEN NEW.action_id LIKE 'create:contact:%' BEGIN SELECT RAISE(ABORT, 'proof fault'); END");
  const failure = await svc.handle("contacts.create", { clientActionId: "fault-contact", name: "不能残默认实体", computeSlots: 5 });
  assert.equal(!failure.ok && failure.error.code, "internal");
  assert.equal(host.listContacts().length, 1);
  assert.equal(all(host.db, "SELECT * FROM gg_contact_config_versions").length, 1);
  run(host.db, "DROP TRIGGER proof_abort");
  const sent = await svc.handle("messages.send", { roomId: group.id, clientActionId: "proof-message", text: "保留这条真实消息" }); assert.ok(sent.ok);
  const task = await svc.handle("tasks.create", { roomId: group.id, clientActionId: "proof-task", title: "保留真实任务" }); assert.ok(task.ok);
  await host.idle();
  const taskId = (task.value as TaskView).id;
  const before = { task: host.taskDoc(taskId), events: all(host.db, "SELECT * FROM events"), cursors: all(host.db, "SELECT * FROM gg_cursor") };
  const update = await svc.handle("contacts.update", { contactId: contact.id, expectedVersion: 1, clientActionId: "proof-update", computeSlots: 1 }); assert.ok(update.ok);
  const roomUpdate = await svc.handle("rooms.update", { roomId: group.id, tempComputeSlots: 0 }); assert.ok(roomUpdate.ok);
  const rollback = await svc.handle("contacts.rollback", { contactId: contact.id, version: 1, expectedVersion: 2, clientActionId: "proof-rollback" }); assert.ok(rollback.ok);
  assert.equal(host.contactDoc(contact.id).value.computeSlots, 2);
  assert.deepEqual(host.contactHistory(contact.id).versions.map((v) => [v.version, v.kind, v.config.computeSlots]), [[3, "rollback", 2], [2, "update", 1], [1, "create", 2]]);
  assert.deepEqual({ task: host.taskDoc(taskId), events: all(host.db, "SELECT * FROM events"), cursors: all(host.db, "SELECT * FROM gg_cursor") }, before);
  await host.close(); host = new Host({ file, dataDir: root, mind, maxDeferMs: 1 }); svc = createService(host);
  const contactReplay = await svc.handle("contacts.create", contactInput);
  const groupReplay = await svc.handle("rooms.createGroup", groupInput);
  assert.deepEqual([contactReplay, groupReplay], [created, groupCreated]);
  assert.deepEqual([host.contactDoc(contact.id).ver, host.contactDoc(contact.id).value.computeSlots, host.roomView(group.id).tempComputeSlots], [3, 2, 0]);
  const conflict = await svc.handle("rooms.createGroup", { ...groupInput, tempComputeSlots: 4 }); assert.equal(!conflict.ok && conflict.error.code, "conflict");
  assert.deepEqual([host.listContacts().length, all(host.db, "SELECT * FROM gg_rooms WHERE kind='group'").length, all(host.db, "SELECT * FROM actions WHERE action_id LIKE 'create:%'").length], [1, 1, 2]);
  assert.deepEqual(host.taskDoc(taskId), before.task);
  console.log(JSON.stringify({ proof: "service/Host/SQLite no-model", contactCreatedSlots: 2, groupCreatedSlots: 3, replayAcrossRestart: true, mutatedRequest: "conflict", badQuota: "invalid_params", failedActionNoDefaultEntity: true, historyVersions: [3, 2, 1], taskMessageCursorPreserved: true, currentGroupSlotsAfterReplay: 0, helperCreate: "not in base; #64/Q13 prerequisite" }, null, 2));
} finally { await host.close(); rmSync(root, { recursive: true, force: true }); }
